-- StudyPilot on Supabase (Postgres)
-- You do NOT have to run this by hand: the app creates everything automatically on first use once DATABASE_URL is set.
-- It is here so you can read / review the data model, or pre-create it from the Supabase SQL editor.
--
-- Layout: one registry table + one schema per learner (learner_<id>), so every learner's data is fully isolated.
-- None of these schemas are exposed through Supabase's public REST API (only the `public` schema is), so the anon key can never read them.

CREATE SCHEMA IF NOT EXISTS studypilot;
CREATE TABLE IF NOT EXISTS studypilot.learners(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, level TEXT DEFAULT 'beginner',
  goal TEXT DEFAULT '', exam_date TEXT DEFAULT '', created DOUBLE PRECISION);;

-- ---- Replace 1 with the learner id (the app does this for you) ----
CREATE SCHEMA IF NOT EXISTS learner_1;
SET search_path TO learner_1, public;

CREATE TABLE IF NOT EXISTS sources(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, kind TEXT, path TEXT, meta TEXT DEFAULT '{}', created DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS units(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_id INTEGER, seq INTEGER, kind TEXT, text TEXT, loc TEXT, label TEXT,
  topic_id INTEGER, subtopic_id INTEGER, concept_ids TEXT DEFAULT '[]');
CREATE TABLE IF NOT EXISTS topics(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, parent_id INTEGER, summary TEXT, order_idx INTEGER);
CREATE TABLE IF NOT EXISTS concepts(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, topic_id INTEGER, subtopic_id INTEGER, name TEXT);
CREATE TABLE IF NOT EXISTS prereqs(topic_id INTEGER, prereq_id INTEGER);
CREATE TABLE IF NOT EXISTS students(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, level TEXT, goal TEXT, exam_date TEXT, created DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS mastery(student_id INTEGER, topic_id INTEGER, p_know DOUBLE PRECISION, stability DOUBLE PRECISION, n_obs INTEGER, last_ts DOUBLE PRECISION,
  PRIMARY KEY(student_id, topic_id));
CREATE TABLE IF NOT EXISTS questions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, qtype TEXT, stem TEXT, options TEXT, answer TEXT, explanation TEXT,
  topic_id INTEGER, subtopic_id INTEGER, unit_id INTEGER, difficulty TEXT, verified INTEGER, verify_note TEXT, extra TEXT, created DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS assessments(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER, kind TEXT, qids TEXT, before TEXT, created DOUBLE PRECISION, finished DOUBLE PRECISION, report TEXT);
CREATE TABLE IF NOT EXISTS mastery_log(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER, topic_id INTEGER, p_know DOUBLE PRECISION, ts DOUBLE PRECISION, src TEXT);
CREATE TABLE IF NOT EXISTS attempts(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER, assessment_id INTEGER, question_id INTEGER,
  response TEXT, correct INTEGER, score DOUBLE PRECISION, ts DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS notes(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_id INTEGER, title TEXT, options TEXT, body TEXT, created DOUBLE PRECISION);

CREATE INDEX IF NOT EXISTS ix_units_source ON units(source_id);
CREATE INDEX IF NOT EXISTS ix_units_topic ON units(topic_id);
CREATE INDEX IF NOT EXISTS ix_attempts_student ON attempts(student_id);
CREATE INDEX IF NOT EXISTS ix_questions_topic ON questions(topic_id);
CREATE INDEX IF NOT EXISTS ix_mastery_log_student ON mastery_log(student_id);;
