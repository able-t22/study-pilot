"""Database layer. One tiny API (q / q1 / ex / many) with two interchangeable backends:

  * SQLite  (default, zero config)           -> one file per learner under data/users/<id>/
  * Postgres / Supabase (set DATABASE_URL)   -> one schema per learner ("learner_<id>") in a single database

All application code keeps using '?' placeholders and plain SQL; this module translates them for Postgres.
Run `python scripts/check_db.py` to verify the connection and create the tables.
"""
import functools, re, sqlite3, threading
from . import config as C

SCHEMA = """
CREATE TABLE IF NOT EXISTS sources(id INTEGER PRIMARY KEY, name TEXT, kind TEXT, path TEXT, meta TEXT DEFAULT '{}', created REAL);
CREATE TABLE IF NOT EXISTS units(id INTEGER PRIMARY KEY, source_id INTEGER, seq INTEGER, kind TEXT, text TEXT, loc TEXT, label TEXT,
  topic_id INTEGER, subtopic_id INTEGER, concept_ids TEXT DEFAULT '[]');
CREATE TABLE IF NOT EXISTS topics(id INTEGER PRIMARY KEY, name TEXT, parent_id INTEGER, summary TEXT, order_idx INTEGER);
CREATE TABLE IF NOT EXISTS concepts(id INTEGER PRIMARY KEY, topic_id INTEGER, subtopic_id INTEGER, name TEXT);
CREATE TABLE IF NOT EXISTS prereqs(topic_id INTEGER, prereq_id INTEGER);
CREATE TABLE IF NOT EXISTS students(id INTEGER PRIMARY KEY, name TEXT, level TEXT, goal TEXT, exam_date TEXT, created REAL);
CREATE TABLE IF NOT EXISTS mastery(student_id INTEGER, topic_id INTEGER, p_know REAL, stability REAL, n_obs INTEGER, last_ts REAL,
  PRIMARY KEY(student_id, topic_id));
CREATE TABLE IF NOT EXISTS questions(id INTEGER PRIMARY KEY, qtype TEXT, stem TEXT, options TEXT, answer TEXT, explanation TEXT,
  topic_id INTEGER, subtopic_id INTEGER, unit_id INTEGER, difficulty TEXT, verified INTEGER, verify_note TEXT, extra TEXT, created REAL);
CREATE TABLE IF NOT EXISTS assessments(id INTEGER PRIMARY KEY, student_id INTEGER, kind TEXT, qids TEXT, before TEXT, created REAL, finished REAL, report TEXT);
CREATE TABLE IF NOT EXISTS mastery_log(id INTEGER PRIMARY KEY, student_id INTEGER, topic_id INTEGER, p_know REAL, ts REAL, src TEXT);
CREATE TABLE IF NOT EXISTS attempts(id INTEGER PRIMARY KEY, student_id INTEGER, assessment_id INTEGER, question_id INTEGER,
  response TEXT, correct INTEGER, score REAL, ts REAL);
CREATE TABLE IF NOT EXISTS reviews(id INTEGER PRIMARY KEY, student_id INTEGER, topic_id INTEGER, card_key TEXT, front TEXT, back TEXT, source TEXT,
  ease REAL, interval REAL, due REAL, reps INTEGER, lapses INTEGER, last REAL, created REAL);
CREATE TABLE IF NOT EXISTS teachbacks(id INTEGER PRIMARY KEY, student_id INTEGER, topic_id INTEGER, body TEXT, score REAL, result TEXT, created REAL);
CREATE TABLE IF NOT EXISTS intake(student_id INTEGER PRIMARY KEY, data TEXT, created REAL);
CREATE TABLE IF NOT EXISTS notes(id INTEGER PRIMARY KEY, source_id INTEGER, title TEXT, options TEXT, body TEXT, created REAL);
"""
INDEXES = """
CREATE INDEX IF NOT EXISTS ix_units_source ON units(source_id);
CREATE INDEX IF NOT EXISTS ix_units_topic ON units(topic_id);
CREATE INDEX IF NOT EXISTS ix_attempts_student ON attempts(student_id);
CREATE INDEX IF NOT EXISTS ix_questions_topic ON questions(topic_id);
CREATE INDEX IF NOT EXISTS ix_mastery_log_student ON mastery_log(student_id);
"""
NO_ID = {"prereqs", "mastery", "intake"}  # tables without a single 'id' column (no RETURNING id on insert)


def pg_schema():
    """Same tables, Postgres types (auto-increment ids that still accept explicit values, double-precision timestamps)."""
    s = SCHEMA.replace("INTEGER PRIMARY KEY", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", s) + INDEXES


# registry of learners (Postgres mode); lives in its own schema so Supabase's public REST API never exposes it
REGISTRY_SQL = """
CREATE SCHEMA IF NOT EXISTS studypilot;
CREATE TABLE IF NOT EXISTS studypilot.learners(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, level TEXT DEFAULT 'beginner',
  goal TEXT DEFAULT '', exam_date TEXT DEFAULT '', created DOUBLE PRECISION);
"""

PG = C.USE_POSTGRES


# =====================================================================  SQLite
_ready = set(); _ready_lock = threading.Lock()


def forget(uid=None):
    """Drop cached 'tables exist' flags (called after a learner's workspace is deleted)."""
    with _ready_lock:
        if uid is None: _ready.clear()
        else: _ready.discard(str(C.workspace(uid) / "studypilot.db"))


def _sqlite_conn():
    path = C.DB_PATH
    key = str(path)
    with _ready_lock:
        if key not in _ready or not path.exists():  # file may have been deleted along with a learner -> recreate tables
            c0 = sqlite3.connect(path, timeout=30)
            try:
                c0.execute("PRAGMA journal_mode=WAL")
                c0.executescript(SCHEMA + INDEXES); c0.commit()
            finally: c0.close()
            _ready.add(key)
    c = sqlite3.connect(path, timeout=30)
    c.row_factory = sqlite3.Row
    c.execute("PRAGMA busy_timeout=30000")
    return c


# =====================================================================  Postgres / Supabase
_pool = None; _pool_lock = threading.RLock(); _schemas = set()


def _get_pool():
    global _pool
    with _pool_lock:
        if _pool is None:
            from psycopg_pool import ConnectionPool
            from psycopg.rows import dict_row
            # prepare_threshold=None: required by Supabase's transaction pooler (port 6543); harmless elsewhere
            _pool = ConnectionPool(C.DATABASE_URL, min_size=1, max_size=C.DB_POOL_MAX, timeout=30, open=True,
                                   kwargs={"row_factory": dict_row, "prepare_threshold": None})
    return _pool


def schema_name(uid=None):
    return f"learner_{int(C.CURRENT_USER.get() if uid is None else uid)}"


@functools.lru_cache(maxsize=512)
def _translate(sql):
    """'?' -> '%s' (outside quoted strings); literal '%' escaped."""
    out, q = [], None
    for ch in sql:
        if q:
            out.append("%%" if ch == "%" else ch)
            if ch == q: q = None
        elif ch in "'\"":
            q = ch; out.append(ch)
        elif ch == "?": out.append("%s")
        elif ch == "%": out.append("%%")
        else: out.append(ch)
    return "".join(out)


def _norm(v):
    if isinstance(v, bool): return int(v)  # sqlite stores bools as ints; Postgres INTEGER columns reject booleans
    if hasattr(v, "item") and hasattr(v, "dtype"): return v.item()  # numpy scalars
    return v


def _args(a): return tuple(_norm(x) for x in (a or ()))


def _ensure_schema(name):
    if name in _schemas: return
    with _pool_lock:
        if name in _schemas: return
        with _get_pool().connection() as c:
            c.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", (name,))
            c.execute(f'CREATE SCHEMA IF NOT EXISTS "{name}"')
            c.execute(f'SET LOCAL search_path TO "{name}", public')
            for stmt in filter(None, (s.strip() for s in pg_schema().split(";"))): c.execute(stmt)
        _schemas.add(name)


def _pg_run(sql, args=(), fetch=False, many_rows=None, public=False):
    if public: path = "studypilot, public"
    else:
        name = schema_name(); _ensure_schema(name); path = f'"{name}", public'
    with _get_pool().connection() as c:  # one transaction per call; commits on exit, rolls back on error
        c.execute(f"SET LOCAL search_path TO {path}")
        cur = c.cursor()
        if many_rows is not None:
            cur.executemany(_translate(sql), [_args(r) for r in many_rows]); return None
        cur.execute(_translate(sql), _args(args))
        if fetch: return cur.fetchall()
        return cur.fetchone() if cur.description else None


def admin_q(sql, args=()):   # registry queries (studypilot schema)
    return _pg_run(sql, args, fetch=True, public=True)


def admin_ex(sql, args=()):
    return _pg_run(sql, args, public=True)


def ensure_registry():
    with _get_pool().connection() as c:
        c.execute("SELECT pg_advisory_xact_lock(hashtext('studypilot_registry'))")
        for stmt in filter(None, (s.strip() for s in REGISTRY_SQL.split(";"))): c.execute(stmt)


def drop_learner_schema(uid):
    name = schema_name(uid)
    with _get_pool().connection() as c: c.execute(f'DROP SCHEMA IF EXISTS "{name}" CASCADE')
    _schemas.discard(name)


# =====================================================================  public API
def init():
    if PG: _ensure_schema(schema_name())
    else: _sqlite_conn().close()


def q(sql, args=()):
    if PG: return list(_pg_run(sql, args, fetch=True))
    c = _sqlite_conn()
    try: return [dict(r) for r in c.execute(sql, args).fetchall()]
    finally: c.close()


def q1(sql, args=()):
    r = q(sql, args)
    return r[0] if r else None


def ex(sql, args=()):
    """Run a write. Returns the new row id for INSERTs into tables that have an 'id' column."""
    if PG:
        m = re.match(r"\s*INSERT\s+INTO\s+(\w+)", sql, re.I)
        if m and m.group(1).lower() not in NO_ID:
            row = _pg_run(sql.rstrip().rstrip(";") + " RETURNING id", args)
            return row["id"] if row else None
        _pg_run(sql, args); return None
    c = _sqlite_conn()
    try:
        cur = c.execute(sql, args); c.commit(); return cur.lastrowid
    finally: c.close()


def many(sql, rows):
    if PG: _pg_run(sql, many_rows=list(rows)); return
    c = _sqlite_conn()
    try: c.executemany(sql, rows); c.commit()
    finally: c.close()


def reset_analysis():
    """Re-analysis wipes everything derived from topics (documented in README)."""
    for t in ("topics", "concepts", "prereqs", "mastery", "mastery_log", "questions", "assessments", "attempts"):
        ex(f"DELETE FROM {t}")
    ex("UPDATE units SET topic_id=NULL, subtopic_id=NULL, concept_ids='[]'")
